function toggleMusica() {
  const audio = document.getElementById('musica-fundo');
  const btn = document.getElementById('btn-music');
  if (!audio) return;
  
  if (audio.paused) {
    audio.play();
    btn.textContent = '⏸️ Pausar';
  } else {
    audio.pause();
    btn.textContent = '▶️ Áudio';
    return;
  }
}

function activateSkill(element) {
  const color = element.getAttribute('data-color');
  
  // Se o card já estiver ativo, desativa
  if (element.classList.contains('active-skill')) {
    element.classList.remove('active-skill');
    element.style.backgroundColor = '#ffffff';
    element.style.color = '#000000';
  } else {
    // Reseta todos os outros cards
    document.querySelectorAll('.skill-card').forEach(card => {
      card.classList.remove('active-skill');
      card.style.backgroundColor = '#ffffff';
      card.style.color = '#000000';
    });
    
    // Ativa apenas o selecionado
    element.classList.add('active-skill');
    if (color) {
      element.style.backgroundColor = color;
      element.style.color = '#ffffff';
    }
  }
}