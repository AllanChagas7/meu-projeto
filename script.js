function changeLanguage(lang) {
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (traducoes[lang] && traducoes[lang][key]) {
      element.textContent = traducoes[lang][key];
    }
  });

  document.querySelectorAll('.btn-lang').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

// ===================================================
// CARROSSEL DE FOTOS
// ===================================================
let currentPhotoIndex = 0;
const totalPhotos = 3;

function moveCarousel(direction) {
  const galleryGrid = document.querySelector('.gallery-grid');
  if (!galleryGrid) return;

  currentPhotoIndex += direction;
  
  if (currentPhotoIndex >= totalPhotos) {
    currentPhotoIndex = 0;
  } else if (currentPhotoIndex < 0) {
    currentPhotoIndex = totalPhotos - 1;
  }
  
  updateCarousel(galleryGrid);
}

function goToPhoto(index) {
  const galleryGrid = document.querySelector('.gallery-grid');
  if (!galleryGrid) return;
  currentPhotoIndex = index;
  updateCarousel(galleryGrid);
}

function updateCarousel(galleryGrid) {
  const card = galleryGrid.querySelector('.gallery-card');
  if (card) {
    const cardWidth = card.offsetWidth + 16;
    galleryGrid.scrollLeft = currentPhotoIndex * cardWidth;
  }
  
  const indicators = document.querySelectorAll('.indicator');
  indicators.forEach((indicator, index) => {
    indicator.classList.toggle('active', index === currentPhotoIndex);
  });
}

// ===================================================
// EVENTOS E INICIALIZAÇÃO
// ===================================================
document.addEventListener('DOMContentLoaded', () => {
  // Carregar idioma salvo
  const savedLang = localStorage.getItem('preferredLang') || 'pt';
  changeLanguage(savedLang);
  
  // Menu Dropdown (Categorias dentro do botão)
  const menuToggle = document.getElementById('menu-toggle');
  const navMenu = document.getElementById('nav-menu');

  if (menuToggle && navMenu) {
    menuToggle.addEventListener('click', (e) => {
      e.stopPropagation();
      navMenu.classList.toggle('open');
      navMenu.classList.toggle('active');
    });
    
    // Fechar menu ao clicar em um link
    navMenu.querySelectorAll('a').forEach(link => {
      link.addEventListener('click', () => {
        navMenu.classList.remove('open');
        navMenu.classList.remove('active');
      });
    });

    // Fechar menu ao clicar fora dele
    document.addEventListener('click', (e) => {
      if (!navMenu.contains(e.target) && !menuToggle.contains(e.target)) {
        navMenu.classList.remove('open');
        navMenu.classList.remove('active');
      }
    });
  }

  // Event Listeners dos Botões de Idioma
  document.querySelectorAll('.btn-lang').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const selectedLang = e.target.getAttribute('data-lang');
      localStorage.setItem('preferredLang', selectedLang);
      changeLanguage(selectedLang);
    });
  });
});

